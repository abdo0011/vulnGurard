"""
Feature 3: SSL/TLS detection, real handshakes.

Starts local HTTPS servers with certificates generated by the `cryptography` package and runs the real crawler and
engine against them, proving that the verifier's error number reaches the detector for a genuinely expired, not yet
valid, mismatched, self-signed or untrusted certificate. `cryptography` is a declared development dependency
(requirements-dev.txt), so a missing install is an ERROR here, never a silent skip. The pure detector tests that do not
need certificates live in test_tls_security.py and have no dependency on it.
"""
import datetime
import json
import re
import ssl
from pathlib import Path

import pytest
from conftest import HTML as HTML_HEADERS
from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import rsa
from cryptography.x509.oid import NameOID

from scanner.detectors import CATEGORIES
from scanner.engine import ScanEngine
from scanner.http_client import FetchError, ScanHTTPClient

TLS = {'ssl_tls'}


NOW = datetime.datetime.now(datetime.timezone.utc)


class Pki:
    def __init__(self, directory):
        self.dir = directory
        self.ca_key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
        name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, 'Test Root CA')])
        self.ca = (x509.CertificateBuilder().subject_name(name).issuer_name(name).public_key(self.ca_key.public_key())
                   .serial_number(x509.random_serial_number()).not_valid_before(NOW - datetime.timedelta(days=30))
                   .not_valid_after(NOW + datetime.timedelta(days=30))
                   .add_extension(x509.BasicConstraints(ca=True, path_length=None), critical=True)
                   .add_extension(x509.SubjectKeyIdentifier.from_public_key(self.ca_key.public_key()), critical=False)
                   .add_extension(x509.KeyUsage(digital_signature=True, key_cert_sign=True, crl_sign=True, content_commitment=False,
                                                key_encipherment=False, data_encipherment=False, key_agreement=False, encipher_only=False,
                                                decipher_only=False), critical=True)
                   .sign(self.ca_key, hashes.SHA256()))
        self.ca_file = self._write('ca.pem', self.ca.public_bytes(serialization.Encoding.PEM))
        self.count = 0

    def _write(self, name, data):
        path = self.dir / name
        path.write_bytes(data)
        return str(path)

    def issue(self, host, *, days_before=1, days_after=30, signer='ca', san=None):
        self.count += 1
        key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
        subject = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, host)])
        sans = [x509.DNSName(h) for h in (san or [host])]
        builder = (x509.CertificateBuilder().subject_name(subject).public_key(key.public_key()).serial_number(x509.random_serial_number())
                   .not_valid_before(NOW - datetime.timedelta(days=days_before)).not_valid_after(NOW + datetime.timedelta(days=days_after))
                   .add_extension(x509.SubjectAlternativeName(sans), critical=False)
                   .add_extension(x509.BasicConstraints(ca=False, path_length=None), critical=True))
        if signer == 'ca':                       # Python 3.13 verifies in strict mode: the leaf needs an Authority Key Identifier
            builder = builder.add_extension(x509.AuthorityKeyIdentifier.from_issuer_public_key(self.ca_key.public_key()), critical=False)
            cert = builder.issuer_name(self.ca.subject).sign(self.ca_key, hashes.SHA256())
        else:                                                                       # 'self' or 'foreign': not chained to our CA
            other = rsa.generate_private_key(public_exponent=65537, key_size=2048) if signer == 'foreign' else key
            issuer = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, 'Unknown CA')]) if signer == 'foreign' else subject
            cert = builder.issuer_name(issuer).sign(other, hashes.SHA256())
        crt = self._write(f'c{self.count}.pem', cert.public_bytes(serialization.Encoding.PEM))
        k = self._write(f'k{self.count}.pem', key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.TraditionalOpenSSL,
                                                                 serialization.NoEncryption()))
        return crt, k


@pytest.fixture(scope='module')
def pki(tmp_path_factory):
    return Pki(tmp_path_factory.mktemp('pki'))


@pytest.fixture
def trusting(pki, monkeypatch):
    """The scanner host trusts the test CA only (OpenSSL reads SSL_CERT_FILE when the default context loads its roots)."""
    monkeypatch.setenv('SSL_CERT_FILE', pki.ca_file)
    monkeypatch.delenv('SSL_CERT_DIR', raising=False)


@pytest.fixture
def engine(lab_config, resolver, clock):
    def factory(target, config, resolver):
        return ScanHTTPClient(target, config, resolver=resolver, clock=clock.now, sleep=clock.sleep)
    return ScanEngine(config=lab_config, resolver=resolver, client_factory=factory)


def scan(engine, srv):
    return engine.run(srv.base + '/', True, TLS)


def serve(make_server, cert, body=b'<a href="/a">a</a>'):
    return make_server({'/': (200, [HTML_HEADERS and ('Content-Type', 'text/html')], body), '/a': (200, [('Content-Type', 'text/html')], b'<p>a</p>')},
                       tls=cert)


def test_trusted_valid_certificate_over_modern_tls_has_no_certificate_finding(make_server, engine, pki, trusting):
    srv = serve(make_server, pki.issue('lab.test'))
    out = scan(engine, srv)
    assert out.status == 'completed' and out.errors == []
    assert {f.extra['rule'] for f in out.findings} == {'TLS-LEGACY-UNTESTED'}
    assert out.requests_used == len(srv.seen) == 2                                  # the detector added no requests
    assert engine.run(srv.base + '/', True, {'cookie_security'}).requests_used == 2
    assert 'TLSv1' in out.findings[0].evidence


def test_an_expired_certificate_is_reported_as_expired(make_server, engine, pki, trusting):
    srv = serve(make_server, pki.issue('lab.test', days_before=10, days_after=-1))
    out = scan(engine, srv)
    f = [x for x in out.findings if x.extra['rule'] == 'TLS-CERT-EXPIRED'][0]
    assert f.confidence == 'Confirmed' and f.severity == 'High' and 'OpenSSL verification error 10' in f.evidence
    assert not [x for x in out.findings if x.extra['rule'] in ('TLS-CERT-HOSTNAME-MISMATCH', 'TLS-CERT-SELF-SIGNED')]
    # pages_crawled counts pages that were FETCHED (len(crawl_result.pages)), not URLs that were attempted. Three requests
    # were attempted (requests_used == 3):
    #   1. '/' with verification: the handshake failed on the expired certificate, so nothing reached the server;
    #   2. '/' again, through Phase 2's depth-0 fallback that retries WITHOUT certificate verification: this is the one
    #      page that was fetched (the server saw exactly this one request), over an unverified connection;
    #   3. the linked '/a' with verification: it failed the same way and has no fallback, so it was never fetched.
    # So pages_crawled == 1 means "the start page was fetched unverified"; it does not mean that TLS verification
    # succeeded, and it says nothing about '/a'. The failure itself was recorded for BOTH attempted URLs below.
    assert out.pages_crawled == 1 and out.requests_used == 3 and srv.paths() == ['/']
    assert f.affected_urls == [srv.base + '/', srv.base + '/a']


