def test_a_handshake_that_fails_for_another_reason_produces_no_finding(make_server, engine, pki, trusting, monkeypatch):
    srv = serve(make_server, pki.issue('lab.test'))

    def refuse(self, method, url, headers, verify_tls):
        raise FetchError('tls_error', 'TLS handshake failed.')
    monkeypatch.setattr(ScanHTTPClient, '_single_request', refuse)
    out = scan(engine, srv)
    assert out.findings == [] and out.status == 'failed'


def test_proxy_environment_variables_do_not_change_the_result(make_server, engine, pki, trusting, monkeypatch):
    for name in ('HTTPS_PROXY', 'https_proxy', 'HTTP_PROXY', 'http_proxy', 'ALL_PROXY'):
        monkeypatch.setenv(name, 'http://127.0.0.1:9')
    srv = serve(make_server, pki.issue('other.test'))
    out = scan(engine, srv)
    assert 'TLS-CERT-HOSTNAME-MISMATCH' in {f.extra['rule'] for f in out.findings}
    assert out.requests_used == engine.run(srv.base + '/', True, {'cookie_security'}).requests_used      # same traffic with no TLS detector


def test_engine_output_contains_no_certificate_material(make_server, engine, pki, trusting, caplog, capsys):
    crt, key = pki.issue('other.test')
    srv = serve(make_server, (crt, key))
    import logging
    with caplog.at_level(logging.DEBUG):
        out = scan(engine, srv)
        print(out, out.findings)
    blob = ' '.join([repr(out), str(out.findings), json.dumps([f.to_dict() for f in out.findings]), caplog.text, capsys.readouterr().out,
                     ' '.join(out.errors + out.notes)])
    pem = Path(crt).read_text()
    assert 'BEGIN' not in blob and pem.splitlines()[1][:30] not in blob and 'Test Root CA' not in blob and '127.0.0.1' not in blob


