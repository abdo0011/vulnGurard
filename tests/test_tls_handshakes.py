def test_the_same_certificate_is_trusted_or_not_depending_only_on_the_scanner_trust_store(make_server, engine, pki, monkeypatch, tmp_path):
    srv = serve(make_server, pki.issue('lab.test'))
    empty = tmp_path / 'empty.pem'
    empty.write_text('')
    monkeypatch.setenv('SSL_CERT_FILE', str(empty))
    monkeypatch.delenv('SSL_CERT_DIR', raising=False)
    untrusted = {f.extra['rule'] for f in scan(engine, srv).findings}
